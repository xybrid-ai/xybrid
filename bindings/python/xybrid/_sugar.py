"""Pythonic conveniences layered onto the generated BoltFFI bindings.

``xybrid/_bolt/`` is generated by ``tools/scripts/gen_python_bolt.py`` and
byte-compared against fresh generator output in ``--check`` mode, so it cannot
carry hand-written ergonomics. The SDK still documents the same surface the
Swift and Kotlin wrappers expose — ``XybridEnvelope.text(...)``,
``result.text``, ``model.model_id``, ``voice.is_female`` — so this module
attaches them to the generated classes when ``xybrid`` is imported.

Patching rather than subclassing is deliberate: the compiled bridge
instantiates the generated classes directly (``_native._register_xybrid_result``
and friends), so instances handed back from a native call would never be of a
subclass. Every addition here is a new name; nothing generated is replaced
except the four ``run*`` methods, which gain a default for their trailing
``options`` argument.

Regeneration safety: ``tests/test_sdk.py`` asserts each patched member is
present, so a generator change that renames or removes one fails the suite
instead of silently dropping the documented API.
"""

from __future__ import annotations

from typing import Any

from . import _bolt
from ._errors import ConfigError

__all__ = ["install"]

_IMAGE_FORMATS = ("png", "jpeg", "webp")


def normalize_image_format(format: str) -> str:
    """Normalize an image format string, mirroring the Rust-side allowlist.

    Raises:
        ConfigError: If ``format`` is not png, jpeg, jpg, or webp.
    """

    # Mirrors xybrid-core ir/envelope.rs; keep in sync when ImageFormat grows.
    normalized = format.strip().lower()
    if normalized == "jpg":
        return "jpeg"
    if normalized in _IMAGE_FORMATS:
        return normalized
    raise ConfigError(f"Unsupported image format '{format}'. Supported formats: png, jpeg, jpg, webp")


def _install_envelope_kind_factories() -> None:
    kind = _bolt.XybridEnvelopeKind

    def text(text: str) -> _bolt.XybridEnvelopeKind:
        """Wrap prompt or completion text."""

        return _bolt.XybridEnvelopeKindText(text=text)

    def audio(data: bytes) -> _bolt.XybridEnvelopeKind:
        """Wrap raw PCM audio bytes."""

        return _bolt.XybridEnvelopeKindAudio(bytes=data)

    def embedding(values: list[float]) -> _bolt.XybridEnvelopeKind:
        """Wrap an embedding vector."""

        return _bolt.XybridEnvelopeKindEmbedding(values=values)

    def image(data: bytes, format: str) -> _bolt.XybridEnvelopeKind:
        """Wrap encoded image bytes. ``format`` is passed through verbatim."""

        return _bolt.XybridEnvelopeKindImage(bytes=data, format=format)

    def multi_part(parts: list[_bolt.XybridEnvelope]) -> _bolt.XybridEnvelopeKind:
        """Wrap several envelopes as one multi-part payload."""

        return _bolt.XybridEnvelopeKindMultiPart(parts=parts)

    # These live on the union base, so `XybridEnvelopeKindAudio.text` resolves
    # to the factory rather than a payload field. Read payloads through
    # `isinstance`, never `getattr` — the result accessors below do.
    kind.text = staticmethod(text)
    kind.audio = staticmethod(audio)
    kind.embedding = staticmethod(embedding)
    kind.image = staticmethod(image)
    kind.multi_part = staticmethod(multi_part)


def _install_envelope_factories() -> None:
    envelope = _bolt.XybridEnvelope
    entry = _bolt.XybridMetadataEntry

    def text(
        content: str,
        voice: str | None = None,
        speed: float | None = None,
        *,
        voice_id: str | None = None,
    ) -> _bolt.XybridEnvelope:
        """Create a text envelope, optionally carrying TTS voice metadata."""

        selected_voice = voice if voice is not None else voice_id
        metadata: list[Any] = []
        if selected_voice is not None:
            metadata.append(entry(key="voice_id", value=selected_voice))
            metadata.append(entry(key="speed", value=str(float(1.0 if speed is None else speed))))
        elif speed is not None:
            metadata.append(entry(key="speed", value=str(float(speed))))
        return envelope(kind=_bolt.XybridEnvelopeKind.text(content), metadata=metadata)

    def audio(pcm_data: bytes, sample_rate: int = 16000, channels: int = 1) -> _bolt.XybridEnvelope:
        """Create an audio envelope with sample-rate and channel metadata."""

        return envelope(
            kind=_bolt.XybridEnvelopeKind.audio(pcm_data),
            metadata=[
                entry(key="sample_rate", value=str(sample_rate)),
                entry(key="channels", value=str(channels)),
            ],
        )

    def embedding(data: list[float]) -> _bolt.XybridEnvelope:
        """Create an embedding envelope from a float vector."""

        return envelope(kind=_bolt.XybridEnvelopeKind.embedding(data), metadata=[])

    def image(data: bytes, format: str) -> _bolt.XybridEnvelope:
        """Create an encoded image envelope for vision-language models.

        Raises:
            ConfigError: If ``format`` is not png, jpeg, jpg, or webp.
        """

        return envelope(
            kind=_bolt.XybridEnvelopeKind.image(data, normalize_image_format(format)),
            metadata=[],
        )

    def user_message(text: str, images: list[_bolt.XybridEnvelope] | None = None) -> _bolt.XybridEnvelope:
        """Create a multi-part user message from prompt text and image envelopes.

        Raises:
            ConfigError: If any entry in ``images`` is not an image envelope.
        """

        image_parts = [] if images is None else images
        if not all(isinstance(part.kind, _bolt.XybridEnvelopeKindImage) for part in image_parts):
            raise ConfigError("XybridEnvelope.user_message accepts only image envelopes")
        parts = [envelope(kind=_bolt.XybridEnvelopeKind.text(text), metadata=[])]
        parts.extend(image_parts)
        return envelope(
            kind=_bolt.XybridEnvelopeKind.multi_part(parts),
            metadata=[entry(key="xybrid.role", value="user")],
        )

    envelope.text = staticmethod(text)
    envelope.audio = staticmethod(audio)
    envelope.embedding = staticmethod(embedding)
    envelope.image = staticmethod(image)
    envelope.user_message = staticmethod(user_message)


def _install_result_accessors() -> None:
    result = _bolt.XybridResult

    # Payload presence follows the envelope kind, not output_type — matching
    # the Swift and Kotlin accessors.
    def text(self: Any) -> str | None:
        """Text payload, or ``None`` when the result is not text."""

        kind = self.envelope.kind
        return kind.text if isinstance(kind, _bolt.XybridEnvelopeKindText) else None

    def audio_bytes(self: Any) -> bytes | None:
        """Audio payload, or ``None`` when the result is not audio."""

        kind = self.envelope.kind
        return kind.bytes if isinstance(kind, _bolt.XybridEnvelopeKindAudio) else None

    def embedding(self: Any) -> list[float] | None:
        """Embedding vector, or ``None`` when the result is not an embedding."""

        kind = self.envelope.kind
        return kind.values if isinstance(kind, _bolt.XybridEnvelopeKindEmbedding) else None

    def reasoning_content(self: Any) -> str | None:
        """Chain-of-thought text carried on the ``reasoning_content`` metadata key."""

        for entry in self.envelope.metadata:
            if entry.key == "reasoning_content":
                return entry.value
        return None

    def success(self: Any) -> bool:
        """Always ``True``; failures raise instead. Shape-compat with Swift/Kotlin."""

        return True

    def is_failure(self: Any) -> bool:
        """``True`` when the result carries no output."""

        return self.output_type == _bolt.XybridOutputType.UNKNOWN

    def latency_seconds(self: Any) -> float:
        """Latency in seconds."""

        return self.latency_ms / 1000.0

    for accessor in (text, audio_bytes, embedding, reasoning_content, success, is_failure, latency_seconds):
        setattr(result, accessor.__name__, property(accessor, doc=accessor.__doc__))


def _install_voice_accessors() -> None:
    voice_info = _bolt.XybridVoiceInfo

    def is_male(self: Any) -> bool:
        """``True`` when the voice gender is male."""

        return self.gender == "male"

    def is_female(self: Any) -> bool:
        """``True`` when the voice gender is female."""

        return self.gender == "female"

    for accessor in (is_male, is_female):
        setattr(voice_info, accessor.__name__, property(accessor, doc=accessor.__doc__))


#: Zero-argument model methods the SDK documents as properties.
_MODEL_PROPERTIES = (
    "model_id",
    "version",
    "output_type",
    "is_loaded",
    "is_cloud_serving",
    "supports_streaming",
    "supports_token_streaming",
    "supports_tool_calling",
    "is_llm",
    "has_voices",
)


def _install_model_accessors() -> None:
    model = _bolt.XybridModel

    for name in _MODEL_PROPERTIES:
        method = model.__dict__[name]
        setattr(model, name, property(method, doc=f"See :meth:`xybrid.XybridModel.{name}`."))

    run = model.__dict__["run"]
    run_stream = model.__dict__["run_stream"]
    run_with_context = model.__dict__["run_with_context"]
    run_stream_with_context = model.__dict__["run_stream_with_context"]

    def _run(self: Any, envelope: Any, options: Any = None) -> Any:
        """Run one inference and return its result."""

        return run(self, envelope, options)

    def _run_stream(self: Any, envelope: Any, options: Any = None) -> int:
        """Start a streaming run and return its stream id."""

        return run_stream(self, envelope, options)

    def _run_with_context(self: Any, envelope: Any, context: Any, options: Any = None) -> Any:
        """Run one inference against a conversation context."""

        return run_with_context(self, envelope, context, options)

    def _run_stream_with_context(self: Any, envelope: Any, context: Any, options: Any = None) -> int:
        """Start a streaming run against a conversation context."""

        return run_stream_with_context(self, envelope, context, options)

    def close(self: Any) -> None:
        """Release the native handle now instead of at garbage collection.

        Idempotent, and what leaving a ``with`` block does. The handle is gone
        afterwards, so calling any other method raises ``TypeError``.
        """

        # The generated finalizer is the release path, and it no-ops once the
        # handle is cleared — so this stays correct if that path changes.
        model.__del__(self)

    def __enter__(self: Any) -> Any:
        return self

    def __exit__(self: Any, exc_type: Any, exc: Any, traceback: Any) -> None:
        self.close()

    model.run = _run
    model.run_stream = _run_stream
    model.run_with_context = _run_with_context
    model.run_stream_with_context = _run_stream_with_context
    model.close = close
    model.__enter__ = __enter__
    model.__exit__ = __exit__


def install() -> None:
    """Attach the SDK conveniences to the generated classes. Idempotent."""

    if getattr(_bolt, "_xybrid_sugar_installed", False):
        return
    _install_envelope_kind_factories()
    _install_envelope_factories()
    _install_result_accessors()
    _install_voice_accessors()
    _install_model_accessors()
    _bolt._xybrid_sugar_installed = True
